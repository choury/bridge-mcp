/** 把 CommonJS 客户端源码包进 __ModuleLoader__。 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../..')
const manifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const source = await readFile(resolve(here, 'index.js'), 'utf8')
const output = resolve(root, 'lib/client.js')

const banner = `/* ${manifest.name} ${manifest.version} — generated by src/client/build.mjs; do not edit. */`
const wrapped = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${source}
    return module.exports;
  }
});
`

await mkdir(dirname(output), { recursive: true })
await writeFile(output, wrapped, 'utf8')
console.log(`wrote ${output} (${Buffer.byteLength(wrapped)} bytes)`)
